/**
 * Turning a generated position into an original one.
 *
 * A script is resolved one of two ways, and the caller does not care which:
 *
 *   source-map  the script carried a `sourceMapURL`, so V8's offsets are mapped
 *                through a real map. `sources` in a map are relative to the
 *                map's own directory (verified in A1: `"../../src/math.ts"` with
 *                an empty `sourceRoot`), so the map must be constructed with its
 *                own URL for `resolvedSources` to come out right.
 *   projection  no map and no sourceMappingURL, as in VS Code's build. The path
 *                is rewritten by rule and the line is taken to be identical,
 *                which is true of a 1:1 build.
 *
 * Anything else — `node:` internals, `eval`, unreadable files — resolves to
 * `null` and is skipped rather than guessed at.
 */
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
  LEAST_UPPER_BOUND,
  TraceMap,
  originalPositionFor,
  type Bias,
} from '@jridgewell/trace-mapping'
import { columnAt, lineAt, type FileCache, type LineIndex } from './line-index.js'
import { projectPath, type ProjectionRule } from './projection.js'
import type { ScriptInfo } from './types.js'

export interface OriginalPosition {
  /** Absolute path of the original source file. */
  file: string
  /** 1-based line in the original file. */
  line: number
}

export interface ScriptResolver {
  readonly via: 'source-map' | 'projection'
  /** Length of the generated script, used to recognise the module body. */
  readonly length: number
  /** Original position of a generated byte offset, or `null` if unmappable. */
  original(offset: number): OriginalPosition | null
}

function decodeDataUri(url: string): string | null {
  const comma = url.indexOf(',')
  if (comma === -1) return null
  const meta = url.slice(5, comma)
  const payload = url.slice(comma + 1)
  if (meta.includes(';base64')) return Buffer.from(payload, 'base64').toString('utf8')
  return decodeURIComponent(payload)
}

function loadMapRaw(sourceMapURL: string, scriptUrl: string): { raw: string; mapUrl: string } | null {
  let resolved: URL
  try {
    resolved = new URL(sourceMapURL, scriptUrl)
  } catch {
    return null
  }
  if (resolved.protocol === 'data:') {
    const raw = decodeDataUri(resolved.href)
    // A data: map has no directory, so relative `sources` resolve against the
    // script itself — the behaviour browsers implement.
    return raw === null ? null : { raw, mapUrl: scriptUrl }
  }
  if (resolved.protocol !== 'file:') return null
  try {
    return { raw: readFileSync(fileURLToPath(resolved), 'utf8'), mapUrl: resolved.href }
  } catch {
    return null
  }
}

function createMapResolver(
  sourceMapURL: string,
  scriptUrl: string,
  index: { starts: number[]; length: number },
): ScriptResolver | null {
  const loaded = loadMapRaw(sourceMapURL, scriptUrl)
  if (loaded === null) return null

  let map: TraceMap
  try {
    map = new TraceMap(loaded.raw, loaded.mapUrl)
  } catch {
    return null
  }

  // `originalPositionFor` reports the map's raw `source` string; the caller
  // needs a path on disk, so resolve each raw source once.
  // `originalPositionFor` reports `source` in its RESOLVED form — a `file:` URL
  // when the map was built with a URL — not the raw string from `map.sources`.
  // Keying only on the raw form makes every lookup miss, and the script then
  // resolves to nothing at all. Index all three spellings.
  const paths = new Map<string, string>()
  map.resolvedSources.forEach((absolute, i) => {
    const raw = map.sources[i]
    const path =
      typeof absolute === 'string'
        ? absolute.startsWith('file:')
          ? fileURLToPath(absolute)
          : absolute
        : typeof raw === 'string' && raw.startsWith('/')
          ? raw
          : null
    if (path === null) return
    if (typeof raw === 'string') paths.set(raw, path)
    if (typeof absolute === 'string') paths.set(absolute, path)
    paths.set(path, path)
  })

  const lookup = (offset: number, bias?: Bias): OriginalPosition | null => {
    const line = lineAt(index, offset)
    const column = columnAt(index, offset)
    const found = originalPositionFor(map, { line, column, bias })
    if (!found.source || found.line === null) return null
    const file = paths.get(found.source)
    if (file === undefined) return null
    return { file, line: found.line }
  }

  return {
    via: 'source-map',
    length: index.length,
    original(offset) {
      // A function's opening brace often has no mapping of its own; fall back to
      // the next mapping after it, which is the enclosing original statement.
      return lookup(offset) ?? lookup(offset, LEAST_UPPER_BOUND)
    },
  }
}

function createProjectionResolver(
  generatedPath: string,
  index: LineIndex,
  rules: ProjectionRule[],
): ScriptResolver | null {
  const projected = projectPath(generatedPath, rules)
  if (projected === null) return null
  return {
    via: 'projection',
    length: index.length,
    original(offset) {
      // A 1:1 build: the compiled file has the same shape as its source, so the
      // generated line carries over to the original unchanged.
      return { file: projected, line: lineAt(index, offset) }
    },
  }
}

export function createScriptResolver(
  scriptUrl: string,
  info: ScriptInfo | undefined,
  options: { projection: ProjectionRule[]; cache: FileCache },
): ScriptResolver | null {
  if (!scriptUrl.startsWith('file:')) return null

  let generatedPath: string
  try {
    generatedPath = fileURLToPath(scriptUrl)
  } catch {
    return null
  }

  const index = options.cache.index(generatedPath)
  if (index === null) return null

  if (info?.sourceMapURL) {
    const viaMap = createMapResolver(info.sourceMapURL, scriptUrl, index)
    if (viaMap) return viaMap
  }
  return createProjectionResolver(generatedPath, index, options.projection)
}
