/**
 * The append-only shard: what a single test run writes on its way past.
 *
 * One JSON line per record, a header first and a footer last. The footer is the
 * point: a run that is killed part-way leaves a file that parses but is missing
 * its end, and a partial run's coverage is *silently wrong* rather than merely
 * incomplete — a test that aborted early executed less than it should have, so
 * its recorded touches under-select. Refusing such a shard is the only safe
 * behaviour, and it is why the footer exists rather than trusting the file.
 *
 * Append-as-you-go rather than write-at-the-end, for the same reason: a crash
 * should leave evidence of how far it got.
 *
 * ## Version 2: raw byte ranges, resolved at build time
 *
 * A v1 shard stored `[file, key, startLine, endLine]` per function — resolved
 * inside every test window. That made the recording cost `O(windows × functions
 * in window)` and was measured at 36× the cost of collecting the coverage
 * (ADR-0002). A v2 shard stores what V8 actually said: per window, the executed
 * functions' byte ranges keyed by script id, plus a table naming each script and
 * function once. Every path, line and ordinal lookup happens in `cbd build`.
 *
 * Three consequences are load-bearing:
 *
 *   A byte range means nothing without the exact bytes it was measured against.
 *   A `script` record therefore carries the file's size and mtime, and the build
 *   refuses a shard whose script no longer matches (`cbd-7d5`). Attributing stale
 *   offsets silently is under-selection, the one failure this project does not
 *   accept.
 *
 *   Function identities are still `name@ordinal`, so the table records V8's own
 *   function name per start offset. That is raw payload data, not resolution: it
 *   is written once per function rather than once per window.
 *
 *   Version 1 is refused rather than misread. Its touch tuples would be parsed as
 *   script ids and offsets and produce a confident, empty map.
 *
 * ## Version 3: a window can cover a group of tests
 *
 * Taking coverage at every test boundary costs two V8 takes per test, and a take
 * walks every loaded function (~13 ms on a large single-process suite). Version 3
 * adds a `group` record: one window's touches, shared by the tests that ran inside
 * it. The touches are stored once rather than copied into each test, and
 * `summarizeShard` expands the record back into ordinary test entries, so the map
 * and everything that reads it are unchanged. Version 2 shards are still read.
 */
import { appendFileSync, writeFileSync } from 'node:fs'
import type { DriftStats } from './types.js'

export const SHARD_VERSION = 3

/**
 * Versions this build reads.
 *
 * v2 and v3 encode a window the same way — script ids to byte ranges — so a v2
 * shard is read as itself, not guessed at. v3 adds the `group` record; a shard
 * whose header says 2 may not contain one, because that is not a shard a v2
 * writer could have produced.
 */
const READABLE_VERSIONS = new Set([2, 3])


/**
 * The map's tuple: `[file, key, startLine, endLine]`, in original coordinates.
 *
 * No longer what a shard stores — a v2 shard holds script ids and byte ranges —
 * but it is still the identity the map and the selector share, and it is what
 * `buildMap` produces once resolution has happened.
 */
export type TouchRef = [file: string, key: string, startLine: number, endLine: number]

/** A generated byte range: the function's start and end offsets in its script. */
export type RawRange = [start: number, end: number]

/**
 * A window's executed functions, keyed by script id.
 *
 * Grouped by script rather than stored as flat tuples because every range in a
 * group shares the script's table row and resolver, which is the work the build
 * does exactly once.
 */
export type ShardTouch = Record<string, RawRange[]>

/** One parsed script, as the recorder first saw it execute. */
export interface ShardScript {
  type: 'script'
  scriptId: string
  url: string
  /**
   * The map `Debugger.scriptParsed` advertised, when it did.
   *
   * Recorded rather than rediscovered at build time because a script the runner
   * compiled in memory (ts-node, for one) has no file on disk carrying a
   * `sourceMappingURL` comment. The map exists only in the script table.
   */
  sourceMapURL?: string
  /** The URL file's size and mtime at recording time; the build refuses a mismatch. */
  size: number
  mtimeMs: number
  /**
   * SHA-256 of the file's bytes at recording time.
   *
   * A suite can rebuild its own `dist` during the run, which changes the mtime
   * without changing a byte. When the mtime differs the build hashes the file and
   * accepts it if the hash matches; a real content change is still refused. Absent
   * on shards written before the field existed, where size/mtime remains the rule.
   */
  hash?: string
  /**
   * Present when V8 compiled text that differs from the file on disk — a loader
   * transformed the module (Vitest/Vite, Jest, ts-node). V8's offsets are into
   * this text, not the file, so the build must convert offsets with these line
   * starts before asking the source map (`cbd-x2j`).
   *
   * Omitted for an untransformed script: the file's own line index is the
   * generated index, and the build already reads it.
   */
  generated?: { lineStarts: number[]; length: number }
}

/** One executed function, written the first time any window reports it. */
export interface ShardFunction {
  type: 'function'
  scriptId: string
  start: number
  end: number
  /** V8's raw name; empty for an anonymous function. The build names the module body. */
  name: string
}

export interface ShardHeader {
  type: 'shard'
  version: number
  commit: string
  pid: number
  startedAt: string
  /**
   * `'service'` when this process is a service being observed, not the process
   * running the tests.
   *
   * The adapters open a window for every test on every recorder, so a service
   * shard names all test titles even though a test that made no request never
   * touched the service. Load attribution must not treat those as observers of
   * the service's module state (`cbd-0na.2`). Absent means a test process.
   */
  role?: 'service'
}

export interface ShardTest {
  type: 'test'
  title: string
  file: string | null
  /**
   * Disambiguates a repeated `(file, title)` in one run.
   *
   * Absent for the first occurrence of a title in a file, then 1, 2, … for later
   * ones. The recorder assigns it in test-start order; a full recording is
   * deterministic. A subset recording that runs only a later duplicate cannot know
   * its full-run ordinal, so the map may merge that shard's window with the first
   * occurrence (`cbd-gkj`).
   */
  ordinal?: number
  /** A non-green test's window is not trustworthy; the map builder drops these. */
  status: 'passed' | 'failed' | 'skipped'
  /**
   * Coverage credited by request correlation, not the owner's own window.
   *
   * It carries touches only; its status is not an outcome. The builder unions the
   * touches into the owner's test entry when that entry is in the map and never
   * creates one from this record.
   */
  attributed?: true
  durationMs: number
  /**
   * The test's title path, when the adapter exposes one. Optional because the
   * contract defaults it to `[title]`; the map keeps the array when it is real.
   */
  titlePath?: string[]
  /** Definition site, when the runner exposes it. Not part of the test id. */
  line?: number
  column?: number
  touches: ShardTouch
  /**
   * Files the test read during its window.
   *
   * A text oracle executes no code from the file it reads, so V8 coverage cannot
   * connect them. The adapter's read tracker records the path instead; a change
   * to it then selects this test. Paths are absolute when recorded and filtered /
   * relocated at build time like every other path.
   */
  reads?: string[]
  /**
   * Directories the test listed. A file added to, removed from, or changed under
   * one of these selects the test — the dependency-direction check is a directory
   * listing, not a read of any one file.
   */
  dirReads?: string[]
  /**
   * Reasons the test declared an invisible dependency (`recordOpaque`).
   *
   * A test that spawns a tool or a service has no path to name. The marker makes
   * it selected by any in-scope change rather than by a guess; the reasons are
   * kept so `explain` can say why.
   */
  opaque?: string[]
  /**
   * Environment variables the test declared, by **hash** of the value it saw.
   *
   * The value is never recorded: a shard is a repository artefact. The hash is
   * unsalted and truncated, so a low-entropy value is still recoverable by guessing. Selection compares the hash of the current value against
   * these, so a changed flag selects the declaring test with no file change and no
   * coverage edge.
   */
  env?: Record<string, string>
}

/**
 * Executed outside any test window. Three buckets, and the difference matters
 * because §8.3 treats them differently: a file reached only by `@load` or
 * `@teardown` is startup code and forces `mode: all`, while `@between` has its
 * own policy knob.
 */
export interface ShardBucket {
  type: 'load' | 'between' | 'teardown'
  touches: ShardTouch
  /**
   * Files a service read outside any test window. Additive: a shard written
   * before this field existed means what it said. The build attributes them like
   * import-phase reads, to every test in the shard.
   */
  reads?: string[]
  dirReads?: string[]
}

/**
 * Files read while a spec file was importing, before any test window.
 *
 * A test helper can read a source file at module scope (a text oracle, a suite
 * builder). There is no test window yet, and the read belongs to every test the
 * spec defines. `file` is the spec the adapter scoped it to, or `null` when the
 * adapter cannot know which file is importing — the build then attributes it to
 * every test in the shard, which is conservative.
 */
export interface ShardLoadReads {
  type: 'loadReads'
  file: string | null
  reads?: string[]
  dirReads?: string[]
  /** Environment variables declared during the import phase, by hash. */
  env?: Record<string, string>
  /**
   * Reasons declared outside any test window (`recordOpaque` between tests or after
   * the last one). The build marks every test the record reaches as opaque.
   */
  opaque?: string[]
  /**
   * Set when the reads came from a service's out-of-window bucket rather than a
   * spec's import phase. A service's module loader reads the source of every module it
   * runs, so the build drops a bucket read of a file the shard has coverage for: that
   * file already has function evidence, and a read edge would send every change to it
   * to every test in the shard.
   */
  bucket?: true
}

/**
 * Tests that share one window, when the run records at group granularity.
 *
 * The `touches` belong to every test in `tests`: a group window cannot say which
 * of its tests executed a range, so each is credited with the union. That
 * over-selects inside the group and never under-selects — the direction a
 * coverage oracle has to fail in.
 */
export interface ShardGroup {
  type: 'group'
  /** The window's executed functions, once for the whole group. */
  touches: ShardTouch
  /** The tests the window covers, in start order. */
  tests: ShardGroupTest[]
  /**
   * Reads a target made during this window, unioned across the group.
   *
   * A service's reads arrive with the window, and a group window cannot say which
   * of its tests drove one. Every test in the group therefore carries them, which
   * over-selects and never under-selects. Each test's own reads stay on its entry.
   */
  reads?: string[]
  dirReads?: string[]
}

/** A group test's identity and evidence; its touches are the group's. */
export type ShardGroupTest = Omit<ShardTest, 'type' | 'touches'>

export interface ShardFooter {
  type: 'end'
  tests: number
  finishedAt: string
  /**
   * How far this run's window boundaries landed from where they were meant, when
   * the source that produced them had a boundary to miss. Absent for a synchronous
   * source, whose take answers in the tick it was asked and has no distance to
   * travel.
   *
   * It is in the record rather than in a caller's memory because it is a property of
   * the run, and a run is read long after the process that produced it has gone. A
   * map built from windows that slid is a map whose attribution is approximate, and
   * the difference between "this run was sharp" and "this run was not" should be
   * legible from the shard alone — the alternative is re-reading the source's
   * docblock and hoping.
   *
   * Additive and optional, so a shard written before this field existed still parses
   * and still means what it said.
   */
  drift?: DriftStats
}

/**
 * Something the run knows it could not record fully.
 *
 * Written before the footer, and only when there is something to say: a clean run
 * writes no health record. Both fields are optional and additive, so a shard from
 * before this record existed keeps the behaviour it always had.
 *
 * `generatedMissing` is a script id whose generated text the source could not
 * produce at the end of the run. `failedTakes` counts boundaries that could not be
 * taken — a dead inspector session, or a queued reply that never arrived — each of
 * which substituted an empty window. Both make the coverage incomplete, and an
 * empty window could have covered any file, which is why the build answers them at
 * map level rather than at one path.
 */
export interface ShardHealth {
  type: 'health'
  generatedMissing?: string[]
  failedTakes?: number
}

export type ShardRecord =
  | ShardHeader
  | ShardScript
  | ShardFunction
  | ShardTest
  | ShardGroup
  | ShardBucket
  | ShardLoadReads
  | ShardHealth
  | ShardFooter

/** One parsed shard, with the name it is known by in a map's provenance. */
export interface ShardInput {
  name: string
  records: ShardRecord[]
}

export class IncompleteShardError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'IncompleteShardError'
  }
}

/**
 * A shard this build cannot read, as distinct from one that is merely incomplete.
 *
 * The message has to say what to do, because the answer is always the same:
 * re-record. There is no useful migration from v1 — its resolved tuples carry no
 * script id, so their offsets cannot be recovered.
 */
export class ShardVersionError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'ShardVersionError'
  }
}

/** Somewhere to append lines. A file in production, a string in tests. */
export interface ShardSink {
  append(line: string): void
  /**
   * Start a new run at this sink's path.
   *
   * A shard is append-only within a run, but a second `cbd collect` at the same
   * path must not inherit the first run's records. The recorder calls this at
   * `runStart`.
   */
  reset?(): void
}

export class FileSink implements ShardSink {
  #path: string
  constructor(path: string) {
    this.#path = path
  }
  append(line: string): void {
    appendFileSync(this.#path, `${line}\n`)
  }
  reset(): void {
    writeFileSync(this.#path, '')
  }
}

export class StringSink implements ShardSink {
  lines: string[] = []
  append(line: string): void {
    this.lines.push(line)
  }
  reset(): void {
    this.lines = []
  }
  get text(): string {
    return this.lines.length === 0 ? '' : `${this.lines.join('\n')}\n`
  }
}

export interface ParseShardOptions {
  /**
   * Accept a shard whose run was interrupted (no `end` record).
   *
   * The default is strict because a partial run's coverage is partial: a test that
   * died mid-window executed less than it should have, and such a window
   * under-selects silently. `cbd build --partial` is the explicit opt-in for a run
   * that was killed deliberately.
   */
  allowIncomplete?: boolean
}

export function parseShard(
  text: string,
  source = '<shard>',
  options: ParseShardOptions = {},
): ShardRecord[] {
  const records: ShardRecord[] = []
  const lines = text.split('\n')
  let lastContent = -1
  lines.forEach((raw, index) => {
    if (raw.trim() !== '') lastContent = index
  })
  for (const [index, raw] of lines.entries()) {
    const line = raw.trim()
    if (line === '') continue
    let parsed: unknown
    try {
      parsed = JSON.parse(line)
    } catch {
      // A killed run is cut mid-record, so its final line may be torn. Under the
      // explicit partial opt-in that line is dropped; any earlier bad line is
      // corruption, not truncation.
      if (options.allowIncomplete === true && index === lastContent) continue
      throw new IncompleteShardError(`${source}:${index + 1} is not valid JSON`)
    }
    records.push(parsed as ShardRecord)
  }

  if (records.length === 0) throw new IncompleteShardError(`${source} is empty`)
  const first = records[0]
  if (first?.type !== 'shard') {
    throw new IncompleteShardError(`${source} does not start with a shard header`)
  }
  if (!READABLE_VERSIONS.has(first.version as number)) {
    // Never guess at another version's meaning. A v1 touch is a resolved tuple and
    // a v2 touch is a script id, so reading one as the other yields a well-formed
    // map in which every test reaches nothing — a confident wrong answer.
    throw new ShardVersionError(
      `${source} is a version ${String(first.version)} shard; this build reads versions ` +
        `${[...READABLE_VERSIONS].join(' and ')}. Re-record the run.`,
    )
  }
  if (first.version === 2 && records.some((record) => record.type === 'group')) {
    throw new IncompleteShardError(
      `${source} is a version 2 shard containing a group record, which only a version 3 ` +
        'writer produces; the shard is inconsistent and its coverage cannot be trusted',
    )
  }
  const last = records[records.length - 1]
  for (let index = 1; index < records.length; index += 1) {
    if (records[index]?.type === 'shard') {
      throw new IncompleteShardError(
        `${source} contains a second shard header at record ${String(index + 1)}; ` +
          'two runs were appended to one path, so the coverage cannot be attributed to one run',
      )
    }
  }
  if (last?.type !== 'end' && options.allowIncomplete !== true) {
    throw new IncompleteShardError(
      `${source} has no end record — the run was interrupted, so its coverage is partial`,
    )
  }
  return records
}

/** Union of a test's own paths with its group's, when there is a group. */
function unionPaths(a: string[] | undefined, b: string[] | undefined): string[] | undefined {
  if (b === undefined || b.length === 0) return a
  if (a === undefined || a.length === 0) return b
  return [...new Set([...a, ...b])].sort()
}

/** Split records back into the buckets a map builder wants. */
export function summarizeShard(records: ShardRecord[]): {
  header: ShardHeader
  tests: ShardTest[]
  load: ShardTouch[]
  between: ShardTouch[]
  teardown: ShardTouch[]
  loadReads: ShardLoadReads[]
  health: ShardHealth[]
  scripts: ShardScript[]
  functions: ShardFunction[]
} {
  const header = records.find((r): r is ShardHeader => r.type === 'shard')
  if (header === undefined) throw new IncompleteShardError('shard has no header')

  const tests: ShardTest[] = []
  const load: ShardTouch[] = []
  const between: ShardTouch[] = []
  const teardown: ShardTouch[] = []
  const loadReads: ShardLoadReads[] = []
  const health: ShardHealth[] = []
  const scripts: ShardScript[] = []
  const functions: ShardFunction[] = []
  for (const record of records) {
    if (record.type === 'test') tests.push(record)
    else if (record.type === 'group') {
      // A group's window is expanded into ordinary test entries, so the map, the
      // selection rules and `explain` never learn that grouping happened.
      for (const test of record.tests) {
        const reads = unionPaths(test.reads, record.reads)
        const dirReads = unionPaths(test.dirReads, record.dirReads)
        tests.push({
          type: 'test',
          ...test,
          touches: record.touches,
          ...(reads === undefined ? {} : { reads }),
          ...(dirReads === undefined ? {} : { dirReads }),
        })
      }
    } else if (
      record.type === 'load' ||
      record.type === 'between' ||
      record.type === 'teardown'
    ) {
      const bucket = record.type === 'load' ? load : record.type === 'between' ? between : teardown
      bucket.push(record.touches)
      // Out-of-window reads have no test to name, so they are filed like reads from
      // a module-scope import the adapter could not attribute: against every test.
      if (record.reads !== undefined || record.dirReads !== undefined) {
        loadReads.push({
          type: 'loadReads',
          file: null,
          bucket: true,
          ...(record.reads === undefined ? {} : { reads: record.reads }),
          ...(record.dirReads === undefined ? {} : { dirReads: record.dirReads }),
        })
      }
    } else if (record.type === 'loadReads') loadReads.push(record)
    else if (record.type === 'health') health.push(record)
    else if (record.type === 'script') scripts.push(record)
    else if (record.type === 'function') functions.push(record)
  }
  return { header, tests, load, between, teardown, loadReads, health, scripts, functions }
}
